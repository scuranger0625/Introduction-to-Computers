/*5_1.算術運算子-四則運算(20.0)*/
#include <stdio.h>
int main() {
    int num1,num2;
    scanf("%d%d",&num1,&num2);
    printf("%d+%d=%d\n",num1,num2,num1+num2);
    printf("%d-%d=%d\n",num1,num2,num1-num2);
    printf("%d*%d=%d\n",num1,num2,num1*num2);
    printf("%d/%d=%d\n",num1,num2,num1/num2);

   return 0;
}
